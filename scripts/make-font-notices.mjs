// Writes THIRD-PARTY-NOTICES.md (the fonts that come with Spadewick, their licences and copyright lines) from resources/fonts.
// Run: node scripts/make-font-notices.mjs   (after scripts/fetch-fonts.mjs)
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'fs'
import { join } from 'path'

const FONTS = 'resources/fonts'
const manifest = JSON.parse(readFileSync(join(FONTS, 'extra/manifest.json'), 'utf8'))
const facesOf = dir => manifest.filter(m => m.file.startsWith(`extra/${dir}/`))
const copyrightOf = text => {
  const lines = [...new Set(text.split(/\r?\n/).map(l => l.trim()).filter(l => /^Copyright\b/i.test(l) && /\b(19|20)\d\d\b/.test(l)))]
  return lines.slice(0, 3).map(l => l.replace(/\s*\(with Reserved Font Names?[^)]*\)\.?/i, '').replace(/\|/g, '/'))
}
/** The copyright string a font file carries in its own name table (name id 0), for a licence file that has no copyright line (the Apache texts). */
function fontCopyright(path) {
  try {
    const b = readFileSync(path)
    const n = b.readUInt16BE(4)
    for (let i = 0; i < n; i++) {
      const o = 12 + i * 16
      if (b.toString('latin1', o, o + 4) !== 'name') continue
      const base = b.readUInt32BE(o + 8), count = b.readUInt16BE(base + 2), str = base + b.readUInt16BE(base + 4)
      for (let k = 0; k < count; k++) {
        const r = base + 6 + k * 12
        if (b.readUInt16BE(r + 6) !== 0) continue
        const len = b.readUInt16BE(r + 8), off = b.readUInt16BE(r + 10), platform = b.readUInt16BE(r)
        const raw = b.subarray(str + off, str + off + len)
        return (platform === 0 || platform === 3 ? Buffer.from(raw).swap16().toString('utf16le') : raw.toString('latin1')).replace(/\s+/g, ' ').trim()
      }
    }
  } catch { /* none */ }
  return ''
}
const kindOf = text => (/SIL OPEN FONT LICENSE/i.test(text) ? 'SIL Open Font License 1.1' : 'Apache License 2.0')
const rfnOf = text => /with Reserved Font Name/i.test(text) || /Reserved Font Name\s+["“]/i.test(text.split('PREAMBLE')[0])

const rows = []
for (const dir of readdirSync(join(FONTS, 'extra'), { withFileTypes: true }).filter(e => e.isDirectory()).map(e => e.name).sort()) {
  const licenceFile = readdirSync(join(FONTS, 'extra', dir)).find(n => /^(OFL|LICENSE)\.txt$/i.test(n))
  const text = readFileSync(join(FONTS, 'extra', dir, licenceFile), 'utf8')
  const faces = facesOf(dir)
  rows.push({ family: [...new Set(faces.map(f => f.family))].join(', '), kind: kindOf(text), file: `resources/fonts/extra/${dir}/${licenceFile}`, copyright: copyrightOf(text).join(' ') || fontCopyright(join(FONTS, faces[0].file)) || 'see the licence file', rfn: rfnOf(text), styles: faces.map(f => f.style).join(', ') })
}

const core = [
  { family: 'Liberation Sans, Liberation Serif, Liberation Mono', kind: 'SIL Open Font License 1.1', file: 'resources/fonts/LICENSE-Liberation-OFL.txt', copyright: 'Copyright The Liberation Fonts Project Authors (https://github.com/liberationfonts)' },
  { family: 'Noto Sans Arabic', kind: 'SIL Open Font License 1.1', file: 'resources/fonts/LICENSE-NotoSansArabic-OFL.txt', copyright: 'Copyright The Noto Project Authors (https://github.com/notofonts/arabic)' },
  { family: 'Noto Sans Hebrew', kind: 'SIL Open Font License 1.1', file: 'resources/fonts/LICENSE-NotoSansHebrew-OFL.txt', copyright: 'Copyright The Noto Project Authors (https://github.com/notofonts/hebrew)' }
]
for (const c of core) if (!existsSync(c.file)) console.warn('missing', c.file)

const table = list => ['| Family | Licence | Copyright | Licence file |', '|---|---|---|---|', ...list.map(r => `| ${r.family} | ${r.kind} | ${r.copyright} | \`${r.file}\` |`)].join('\n')
const out = `# Third-party notices: fonts

Spadewick ships with free, open-licence fonts so that card text can be set in many typefaces without anyone importing a file.
This page lists every one of them with its licence and copyright holder. The full licence text of each family is in the file named in
the last column, which is installed with the application (the \`fonts\` folder next to it). Do not remove those files: both licences
require the licence and the copyright notice to travel with the font.

Generated by \`scripts/make-font-notices.mjs\` from \`resources/fonts\`; the fonts were fetched by \`scripts/fetch-fonts.mjs\` from the Google Fonts
repository (https://github.com/google/fonts) on 2026-10-10. Nothing here is legal advice.

## What the licences allow, in short

- **SIL Open Font License 1.1 (OFL)** and **Apache License 2.0**: the fonts may be used for any purpose, commercial included. Cards,
  PDFs and images made with them, and games printed or sold, carry no obligation. Embedding the fonts in a PDF is allowed.
- The fonts may be copied and redistributed (Spadewick does, inside the application) as long as the licence text and copyright notice
  stay with them. They may not be **sold on their own** (OFL).
- A font that is **changed** and shared again must not use a Reserved Font Name of the original (OFL) and must keep its licence.
  Spadewick uses the fonts as they were published and does not change them (a Bold that a family lacks is only drawn heavier on screen
  and in export, not saved as a new font).
- Fonts a person imports into a project are that person's own responsibility: Spadewick does not check their licence.

## Fonts included with Spadewick

${table(core)}

## Extra families (resources/fonts/extra)

${table(rows)}

${rows.filter(r => r.rfn).length ? `Families whose licence names a Reserved Font Name: ${rows.filter(r => r.rfn).map(r => r.family).join('; ')}. This only matters if you modify and redistribute the font itself.\n` : ''}
## Adding or removing a font

1. Add the font files and the family's \`OFL.txt\` or \`LICENSE.txt\` to a folder under \`resources/fonts/extra/\` and add the faces to \`manifest.json\`
   (or run \`scripts/fetch-fonts.mjs\` with a clone of the Google Fonts repository after editing its list).
2. Run \`node scripts/make-font-notices.mjs\` to rewrite this page.
3. \`tests/integration/bundledFonts.test.js\` checks that every bundled family has a licence file that is the OFL or the Apache licence.
`
writeFileSync('THIRD-PARTY-NOTICES.md', out)
console.log(`wrote THIRD-PARTY-NOTICES.md: ${rows.length} extra families, ${core.length} core entries`)
